/* Keep the existing BibTeX renderer; enhance its generated bibliography. */
(() => {
  const display = document.getElementById('bibtex_display');
  const status = document.getElementById('publication-status');
  const search = document.getElementById('searchbar');
  const year = document.getElementById('yearselect');
  const project = document.getElementById('projectselect');
  let ready = false;
  const initialize = () => {
    const entries = [...display.querySelectorAll('.bibtexentry')];
    if (!entries.length || ready) return;
    ready = true;
    observer.disconnect();
    // The source bibliography contains both bare DOIs and full DOI URLs.
    display.querySelectorAll('a[href]').forEach(link => {
      const href = link.getAttribute('href').trim();
      if (/^10\.\d{4,9}\//.test(href)) link.href = 'https://doi.org/' + href;
    });
    // Search literal text so punctuation such as brackets is safe to enter.
    window.jQuery('.bibtex_search').off('keyup change');
    const records = entries.map(element => ({
      element,
      text: element.textContent.toLocaleLowerCase(),
      year: (element.querySelector('.year')?.textContent || '').trim(),
      projects: (element.querySelector('.projects')?.textContent || '').toLocaleLowerCase().split(',').map(s => s.trim())
    }));
    const filter = () => {
      const terms = search.value.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
      let count = 0;
      records.forEach(record => {
        const yearMatches = !year.value || year.value.split('|').includes(record.year);
        const projectMatches = !project.value || record.projects.includes(project.value.toLocaleLowerCase());
        const match = yearMatches && projectMatches && terms.every(term => record.text.includes(term));
        record.element.style.display = match ? '' : 'none';
        if (match) count++;
      });
      // Year sections generated by the original library have a templates container.
      display.querySelectorAll('.templates').forEach(container => {
        const visible = [...container.querySelectorAll('.bibtexentry')].some(item => item.style.display !== 'none');
        container.parentElement.style.display = visible ? '' : 'none';
      });
      status.textContent = count ? `${count} of ${entries.length} publications` : 'No publications found. Try another keyword, year, or project.';
    };
    search.addEventListener('input', filter);
    year.addEventListener('change', filter);
    project.addEventListener('change', filter);
    filter();
  };
  const observer = new MutationObserver(initialize);
  observer.observe(display, {childList: true, subtree: true});
  initialize();
  window.setTimeout(() => {
    if (!ready) status.textContent = 'The publication list could not be loaded. Please reload the page or download the bibliography above.';
  }, 15000);
})();
